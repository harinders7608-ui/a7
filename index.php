<section class="section">
  <div class="container-narrow">
    <div class="section-header">
      <span class="section-tag">Aviator Guidance</span>
      <h2 class="section-title">Frequently Asked Inquiries</h2>
      <p class="section-lead">
        Essential knowledge regarding shearling pelt selection, sub-zero care, and bespoke sizing.
      </p>
    </div>
    <div class="faq-list">
      <div class="faq-item">
        <button class="faq-question">
          <span>What is the difference between genuine shearling and faux fleece lining?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Genuine shearling is a single natural pelt where the soft wool fleece and outer leather hide are organically united as grown by nature. Faux shearling consists of synthetic polyester fleece glued to split leather or vinyl, which traps sweat, breaks down, and lacks the natural breathability and sub-zero thermal performance of sheepskin.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>How heavy is an authentic USAAF B-3 bomber jacket?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          An authentic B-3 flight jacket crafted from 25mm American sheepskin fleece and heavy steerhide welts weighs approximately 6.5 to 8.5 pounds (3 to 4 kilograms). The weight distributes evenly across the shoulders, providing a reassuring feeling of armored warmth.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>How should I protect and maintain the leather exterior in rain or snow?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Natural shearling has a water-resistant polyacrylic finish that sheds light rain and snow easily. If your jacket gets wet, shake off excess moisture and hang it on a wide wooden hanger at room temperature away from direct heat. Apply natural neat's-foot oil or beeswax leather balm once a year to keep the leather supple.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>Why are the seams welted with horsehide strips?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          When thick sheepskin pelts are stitched together, the seam needle holes can permit cold wind to penetrate. Horsehide welt strips are folded over every exterior seam and double-stitched, creating an airtight, windproof seal that prevents seam tearing under extreme movement.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>Can I visit the 181 Mercer Street atelier for a bespoke fitting?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Yes. We welcome clients to our Manhattan atelier at 181 Mercer Street by appointment. You can try on archive flight jacket silhouettes, inspect raw shearling pelts, select custom zipper finishes, and have precise anatomical body measurements taken.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>What warranty accompanies an AviatorCoatUp flight jacket?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Every jacket includes a lifetime craftsmanship warranty covering all seam stitching, solid brass Talon hardware, and buckle attachments under standard wear. We maintain archival repair ledgers for all commissioned outerwear.
